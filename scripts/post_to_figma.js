import fs from 'fs';

const token = process.env.FIGMA_TOKEN || '';
const fileKey = 'B7iFAyyV2t5RrlpxQy8UWh';

async function postComment(message, x, y) {
  try {
    const res = await fetch(`https://api.figma.com/v1/files/${fileKey}/comments`, {
      method: 'POST',
      headers: {
        'X-Figma-Token': token,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        message,
        client_meta: { x, y }
      })
    });

    if (!res.ok) {
      const err = await res.text();
      throw new Error(`HTTP ${res.status}: ${err}`);
    }

    const data = await res.json();
    console.log(`[POSTED] Comment at (${x}, ${y}): ${message.slice(0, 45)}... (id: ${data.id})`);
    return data;
  } catch (e) {
    console.error(`Error posting comment:`, e.message);
  }
}

